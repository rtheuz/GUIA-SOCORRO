import { chromium } from '@playwright/test';
const browser=await chromium.launch({headless:true, ...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {})});
const context=await browser.newContext({viewport:{width:390,height:844},geolocation:{latitude:-23.6635,longitude:-46.5300,accuracy:15},permissions:['geolocation']});
const page=await context.newPage();
page.on('pageerror',error=>console.error('PAGE ERROR',error));
page.on('worker',worker=>console.log('WORKER:',worker.url()));
page.on('requestfailed',request=>console.log('REQUEST FAILED:',request.url(),request.failure()?.errorText));
const base=process.env.TEST_BASE_URL || 'http://127.0.0.1:4173';
const manifest=await (await context.request.get(`${base}/manifest.webmanifest`)).json();
if(manifest.start_url!=='/' || manifest.scope!=='/') throw new Error('O atalho instalado ainda abre no caminho antigo');
await page.goto(`${base}/GUIA-SOCORRO/`);
await page.waitForURL(`${base}/`,{timeout:10000});
await page.getByLabel('Abrindo Guia Socorro').waitFor({state:'visible',timeout:3000});
await page.getByRole('button',{name:/UBS \/ UPA/}).click();
await page.getByRole('button',{name:'Voltar'}).click();
if(await page.getByLabel('Abrindo Guia Socorro').count()) throw new Error('A introdução voltou a aparecer');
await page.goto(`${base}/emergencia/engasgo`);
const whatToDo=page.getByRole('heading',{name:'O que fazer',exact:true}).locator('..').locator('li');
if(await whatToDo.count()!==1 || (await whatToDo.first().innerText()).replace(/\s+/g,' ').trim()!=='1 Ligue 192 (SAMU) imediatamente') throw new Error('A área O que fazer foi alterada');
await page.goto(`${base}/unidades`);
await page.evaluate(()=>navigator.serviceWorker.ready);
await page.getByLabel('Buscar por nome, rua ou bairro').fill('UPA Perimetral');
await page.getByRole('button',{name:'Rota offline'}).click();
await page.getByRole('button',{name:'Baixar mapa offline'}).click();
await page.getByText('Mapa disponível neste aparelho.').waitFor({timeout:60000});
await page.getByRole('button',{name:'A pé'}).click();
await page.getByRole('button',{name:'Baixar mapa offline'}).click();
await page.getByText('Mapa disponível neste aparelho.').waitFor({timeout:60000});
await context.setOffline(true);
await page.getByRole('button',{name:'Calcular rota a pé'}).click();
await page.getByText(/restantes/).waitFor({timeout:15000}).catch(async error=>{console.error('TELA:',await page.locator('body').innerText());throw error;});
console.log('A PÉ OFFLINE:',await page.getByText(/restantes/).innerText());
await page.reload();
await page.getByLabel('Buscar por nome, rua ou bairro').fill('UPA Perimetral');
await page.getByRole('button',{name:'Rota offline'}).click();
await page.getByText('Mapa disponível neste aparelho.').waitFor({timeout:20000});
await page.getByRole('button',{name:'Calcular rota de carro'}).click();
await page.getByText(/restantes/).waitFor({timeout:60000});
console.log('CARRO OFFLINE APÓS RECARREGAR:',await page.getByText(/restantes/).innerText());
console.log('MAPA:',await page.getByRole('img',{name:/Mapa de navegação/}).count());
if(process.env.NAV_SCREENSHOT) await page.screenshot({path:process.env.NAV_SCREENSHOT});
const before=await page.getByText(/restantes/).innerText();
await context.setGeolocation({latitude:-23.6635,longitude:-46.5295,accuracy:15});
await page.waitForFunction(old=>[...document.querySelectorAll('p')].some(p=>p.textContent?.includes('restantes') && p.textContent!==old),before,{timeout:15000});
console.log('GPS ATUALIZADO:',await page.getByText(/restantes/).innerText());
await page.goto(`${base}/GUIA-SOCORRO/`);
await page.waitForURL(`${base}/`,{timeout:10000});
await page.getByRole('button',{name:/UBS \/ UPA/}).waitFor();
console.log('ATALHO ANTIGO OFFLINE: redirecionado para a página inicial');
await browser.close();
