import { chromium } from '@playwright/test';
const browser=await chromium.launch({headless:true, ...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {})});
const context=await browser.newContext({geolocation:{latitude:-23.6635,longitude:-46.5300,accuracy:15},permissions:['geolocation']});
const page=await context.newPage();
page.on('pageerror',error=>console.error('PAGE ERROR',error));
page.on('worker',worker=>console.log('WORKER:',worker.url()));
page.on('requestfailed',request=>console.log('REQUEST FAILED:',request.url(),request.failure()?.errorText));
const base=process.env.TEST_BASE_URL || 'http://127.0.0.1:4173';
await page.goto(base);
await page.getByRole('button',{name:/UBS \/ UPA/}).click();
await page.getByRole('button',{name:'Voltar'}).click();
if(await page.getByText('Informação que salva vidas').count()) throw new Error('A introdução voltou a aparecer');
await page.goto(`${base}/unidades`);
await page.evaluate(()=>navigator.serviceWorker.ready);
await page.getByLabel('Buscar por nome, rua ou bairro').fill('UPA Perimetral');
await page.getByRole('button',{name:'Rota offline'}).click();
await page.getByRole('button',{name:'Baixar mapa offline'}).click();
await page.getByText('Mapa disponível neste aparelho.').waitFor({timeout:60000});
await page.getByRole('button',{name:'A pé'}).click();
await page.getByRole('button',{name:'Baixar mapa offline'}).click();
await page.getByText('Mapa disponível neste aparelho.').waitFor({timeout:60000});
await context.setOffline(true);
await page.getByRole('button',{name:'Calcular rota a pé'}).click();
await page.getByText(/Trajeto estimado:/).waitFor({timeout:15000}).catch(async error=>{console.error('TELA:',await page.locator('body').innerText());throw error;});
console.log('A PÉ OFFLINE:',await page.getByText(/Trajeto estimado:/).innerText());
await page.reload();
await page.getByLabel('Buscar por nome, rua ou bairro').fill('UPA Perimetral');
await page.getByRole('button',{name:'Rota offline'}).click();
await page.getByText('Mapa disponível neste aparelho.').waitFor({timeout:20000});
await page.getByRole('button',{name:'Calcular rota de carro'}).click();
await page.getByText(/Trajeto estimado:/).waitFor({timeout:60000});
console.log('CARRO OFFLINE APÓS RECARREGAR:',await page.getByText(/Trajeto estimado:/).innerText());
console.log('INSTRUÇÕES:',await page.locator('ol li').count());
await browser.close();
